// npm run metrics: runs the canonical bodies through the measurement course (levels.md §1)
// and writes LEVEL_METRICS.md. Level dimensions are chosen from this table.
import { writeFileSync } from 'node:fs';
import { World } from '../src/sim/world';
import { CANON, GROUND_Y } from '../src/sim/canon';
import { WORLD } from '../src/tuning';
import { spawn, run, walkSpeed, reachHeight, jumpHeight } from './measure';
import type { Creature } from '../src/sim/creature';

const BODIES = ['stick400', 'stick700', 'stick1100', 'spider', 'worm', 'box', 'giant', 'hopper', 'reacher', 'bruiser', 'floater'];
const FLOOR = WORLD.floorY;

/** Mean horizontal speed up a 20° ramp (px/s), from the foot of the ramp to 300 px along it. */
function slopeSpeed(name: string): number {
  const rise = Math.tan((20 * Math.PI) / 180);
  const x0 = 220,
    x1 = 720;
  const w = new World({ seed: 1, terrain: [[{ x: x0, y: FLOOR }, { x: x1, y: FLOOR - (x1 - x0) * rise }, { x: x1 + 200, y: FLOOR - (x1 - x0) * rise }, { x: x1 + 200, y: FLOOR }]] });
  const [cr] = spawn(w, CANON[name](110));
  if (!cr) return 0;
  w.toyTarget = { x: 700, y: FLOOR - 400 };
  let tIn = -1,
    tOut = -1;
  run(w, 12, () => {
    const x = w.centroid(cr).x;
    if (tIn < 0 && x > x0 + 30) tIn = w.t;
    if (tOut < 0 && x > x0 + 330) tOut = w.t;
  });
  if (tIn < 0) return 0;
  if (tOut < 0) return (w.centroid(cr).x - (x0 + 30)) / (w.t - tIn) > 5 ? -1 : 0; // -1: started up, stalled
  return 300 / (tOut - tIn);
}

/** Furthest a hand gets from the body's centre, sideways, with a target off to the side. */
function sideReach(name: string): number {
  const w = new World({ seed: 1 });
  const [cr] = spawn(w, CANON[name](200));
  if (!cr) return 0;
  const hands = cr.limbs.filter((l) => !l.foot);
  const c0 = w.centroid(cr);
  w.toyTarget = { x: 700, y: c0.y };
  let best = 0;
  run(w, 3, () => {
    const c = w.centroid(cr);
    const pts = hands.length ? hands.map((l) => l.tip) : cr.ids;
    for (const i of pts) best = Math.max(best, w.P.x[i] - c.x);
  });
  return best;
}

/** Seconds to cross a 200 px gap between two ledges, or null if it falls or stalls. */
function gapTime(name: string): number | null {
  const L = 250,
    R = 450;
  const w = new World({
    seed: 1,
    floor: false,
    terrain: [
      [{ x: -200, y: FLOOR }, { x: L, y: FLOOR }, { x: L, y: 1600 }, { x: -200, y: 1600 }],
      [{ x: R, y: FLOOR }, { x: 920, y: FLOOR }, { x: 920, y: 1600 }, { x: R, y: 1600 }],
    ],
  });
  const [cr] = spawn(w, CANON[name](110));
  if (!cr) return null;
  w.toyTarget = { x: 680, y: FLOOR - 10 };
  let tStart = -1,
    tDone = -1,
    fell = false;
  run(w, 12, () => {
    const c = w.centroid(cr);
    if (tStart < 0 && c.x > L - 120) tStart = w.t;
    if (tDone < 0 && allPast(w, cr, R + 10)) tDone = w.t;
    if (lowest(w, cr) > FLOOR + 120) fell = true;
  });
  if (fell || tDone < 0) return null;
  return tDone - Math.max(0, tStart);
}

function allPast(w: World, cr: Creature, x: number) {
  for (const i of cr.ids) if (w.P.x[i] < x) return false;
  return true;
}
function lowest(w: World, cr: Creature) {
  let y = -Infinity;
  for (const i of cr.ids) y = Math.max(y, w.P.y[i]);
  return y;
}

const fmt = (v: number | null, unit = '') => (v === null ? "can't" : v < 0 ? 'stalls' : `${v.toFixed(0)}${unit}`);
const rows = BODIES.map((n) => {
  const w = new World({ seed: 1 });
  const [cr] = spawn(w, CANON[n](360));
  const kind = cr ? `${cr.kind} / ${cr.gait}` : 'none';
  const size = cr ? cr.stats.size : 0;
  return {
    n,
    kind,
    size,
    mass: cr ? cr.stats.mass : 0,
    walk: walkSpeed(n),
    slope: slopeSpeed(n),
    reachUp: reachHeight(n),
    reachSide: sideReach(n),
    jump: jumpHeight(n),
    gap: gapTime(n),
  };
});

let md = `# Level metrics

Generated by \`npm run metrics\` from the simulation (levels.md §1). Do not edit by hand. Ground is y = ${GROUND_Y}; heights are px above it.

| body | kind / gait | size px | mass | walk px/s | 20° slope px/s | reach up px | reach sideways px | jump px | 200 px gap |
|---|---|---|---|---|---|---|---|---|---|
`;
for (const r of rows)
  md += `| ${r.n} | ${r.kind} | ${r.size.toFixed(0)} | ${r.mass.toFixed(1)} | ${fmt(r.walk)} | ${fmt(r.slope)} | ${fmt(r.reachUp)} | ${fmt(r.reachSide)} | ${fmt(r.jump)} | ${r.gap === null ? "can't" : r.gap.toFixed(1) + ' s'} |\n`;
md += `
Not measured yet (need systems from later phases): bomb throw distance (grab and throw), crusher force held for 4 s (crusher hazard), wind walked against and buoyancy margin with Little Guy (water and wind, before Chapter 4).
`;
writeFileSync('LEVEL_METRICS.md', md);
console.log(md);
